"""Freshness guard: dev-class docs carry owner/last-reviewed headers.

Reads docs/README.md rows tagged `dev`; every listed file must contain
`owner:`, `last-reviewed:`, and `review-interval:` (the freshness contract).
Warn-only for now; full review-date enforcement is a separate decision.
"""
from __future__ import annotations

import fnmatch
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "docs" / "README.md"


def _dev_rows() -> list[str]:
    rows = []
    for line in REGISTRY.read_text().splitlines():
        m = re.match(r"\| `([^`]+)` \| dev \|", line)
        if m:
            rows.append(m.group(1))
    return rows


def test_dev_docs_carry_freshness_headers():
    tracked = set()
    import subprocess
    out = subprocess.check_output(["git", "ls-files", "*.md"], cwd=ROOT, text=True)
    tracked.update(out.splitlines())
    missing = []
    for pat in _dev_rows():
        files = fnmatch.filter(tracked, pat) if any(c in pat for c in "*?[]") else ([pat] if pat in tracked else [])
        # oto/README.md is generated by oto.readme_gen; not maintained by hand.
        files = [f for f in files if f != "oto/README.md"]
        for f in files:
            text = (ROOT / f).read_text(errors="ignore")
            if "last-reviewed:" not in text or "review-interval:" not in text:
                missing.append(f)
    assert not missing, f"docs missing freshness headers: {missing}"
