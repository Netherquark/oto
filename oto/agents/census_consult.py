"""Automated census consult -- corpus priors and gate-legal ladders for a new device.

Owns: turning the measured corpus (through the same census machinery the
--harness tools use) and the CPU gates into a potential-configs markdown for
a device oto has never seen. Everything here is CPU-only; no GPU, no network.
Does NOT own: benchmarks (`oto.runners`), the ledger (`oto.ledger`), the overlay
emission (`oto.harness.candidate_overlay`), or the device docs (agent-1/agent-2).
Public API: consult.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from oto.device import loader as _loader
from oto.harness.candidate_rows import FAMILY_DTYPE, LADDER, PATTERNS, TARGET_CELLS
from oto.runners.result_paths import results_rel
from oto.tensile.candidate import CandidateGenerator
from oto.tensile.gates.occupancy import ldspad_feasible

_KERNEL_DB = Path(results_rel("analysis", "kernel_db.json"))


def _ceilings(p) -> dict[str, Any]:
    """The practical ceilings per family from the profile."""
    return {family: float(p.realistic_ceilings.get(family, 0))
            for family in TARGET_CELLS}


def _corpus_priors(base_dir: Path) -> dict[tuple[str, int], dict[str, Any]]:
    """Best-known (family, side) rows from the local kernel_db."""
    path = Path(base_dir) / _KERNEL_DB
    if not path.exists():
        return {}
    try:
        db = json.loads(path.read_text())
    except json.JSONDecodeError:
        return {}
    from oto.harness.cell_knob_diff import _winner_per_cell
    rows: list[dict[str, Any]] = []
    _floor_prefix = _loader.spoof_prefix()
    for run_id, run_rows in db.items():
        if str(run_id).startswith(f"{_floor_prefix}_ref"):
            continue
        rows.extend(run_rows)
    winners = _winner_per_cell(rows)
    return {cell: w for cell, w in winners.items()
            if w.get("gflops_median") is not None}


def _gate_ladder(base_dir: Path, profile) -> dict[str, list[dict[str, Any]]]:
    """Run the per-family tile ladders through validate_config."""
    gen = CandidateGenerator(Path(base_dir), registry=None)
    out: dict[str, list[dict[str, Any]]] = {}
    for fam, ladder in LADDER.items():
        rows: list[dict[str, Any]] = []
        for tile in ladder:
            knobs = {k: tile[k] for k in
                     ("MacroTile", "ThreadTile", "VectorWidth", "DepthU") if k in tile}
            knobs = _normalise_kernels(knobs)
            pattern = PATTERNS.get(fam, ("Ailk_Bjlk",))[0]
            config = {"Architecture": profile.codename,
                      "DataType": FAMILY_DTYPE[fam],
                      "FamilyLabel": fam,
                      "ScheduleName": "isa",
                      "ContractionPattern": pattern,
                      "ProblemType": "Contraction",
                      **knobs}
            ok, why = gen.validate_config(config, profile=profile)
            ok_p, why_p = ldspad_feasible(config, profile=profile)
            legal = bool(ok and ok_p)
            rows.append({"tile": knobs, "pattern": pattern, "legal": legal,
                         "why": why if not ok else why_p})
        out[fam] = rows
    return out


def _normalise_kernels(knobs: dict[str, Any]) -> dict[str, Any]:
    out = {}
    for k, v in knobs.items():
        if k == "VectorWidth":
            out[k] = int(v)
        elif k == "DepthU":
            out[k] = int(v)
        else:
            out[k] = v
    return out


def _render_device(p, base_dir: Path) -> str:
    lines = [f"# {p.codename} — potential configs (agentic consult)", "",
             "DRAFT — generated by the agentic census consult",
             "(CPU-only; no GPU measurements made yet for this device).", "",
             "## 1. The device", "",
             f"- codename: `{p.codename}`",
             f"- ISA: `({', '.join(str(i) for i in p.isa)})`",
             f"- Compute units: {p.num_cus}",
             f"- SIMDs per CU: {p.simds_per_cu}",
             f"- Wavefront lanes: {p.lanes_per_simd}",
             f"- Clock: {p.max_clock_mhz} MHz",
             f"- LDS: {p.lds_per_cu_kb} KiB/CU",
             f"- L2: {p.l2_size_kb} KiB",
             f"- MFMA: {p.has_mfma}; DP4A: {p.has_dp4a}; packed BF16: {p.has_packed_bf16}",
             f"- VGPR file/CU: {p.vgpr_per_cu}", ""]
    if getattr(p, "spoof_reference", ""):
        lines += [f"- spoof reference (decoder anchor): `{p.spoof_reference}`",
                  ""]
    return "\n".join(lines) + "\n"


def _render_ceilings(p, priors) -> str:
    lines = ["## 2. Ceilings", "",
             "Practical ceilings from the profile (BLAS-8 complex unit, clock-",
             "normalised). These are bounds, not benchmarks.", "",
             "| family | ceiling (GFLOP/s) |", "|---|---|"]
    for fam, ceil in sorted(_ceilings(p).items()):
        lines.append(f"| {fam} | {ceil:.1f} |")
    lines.append("")
    return "\n".join(lines) + "\n"


def _render_taxa(p) -> str:
    lines = ["## 3. Rejection taxa (structurally illegal on this device)", ""]
    if not p.has_mfma:
        lines += ["- Complex families (CC/ZZ): `GlobalSplitU > 1` refused — no",
                  "  MFMA; the k-split path needs `_GlobalAccumulation`, which",
                  "  only MFMA parts provide."]
    lines += ["- UnrollMajorLDS/LdsBlockSizePerPad: refused by Tensile's classic",
              "  VALU path (SolutionStructs warnings; not gate-checkable without",
              "  a per-config probe, so flagged here for the operator).",
              "- Complex accumulator footprint 2x: TT caps at 4x4 for CC/ZZ at",
              "  DU >= 8; wider tiles overflow the register file (Tensile error 4).",
              "- Widest legal MacroTile (universally, by accumulator budget):",
              "  SS/HH 128x64, DD 128x32, CC 128x64 (MT area 16384/R=4), ZZ 64x64.",
              ""]
    return "\n".join(lines) + "\n"


def _render_priors(priors) -> str:
    lines = ["## 4. Priors from the reference corpus (a neighbouring device)",
             "",
             "These are winners measured on a *different* device. They are",
             "priors for where to look first, NOT claims about this part.", ""]
    if not priors:
        lines += ["No kernel_db.json found for the base directory; skipping.",
                  ""]
        return "\n".join(lines) + "\n"
    lines += ["| cell | ref winner | median GFLOP/s |",
              "|---|---|---|"]
    for (fam, side), w in sorted(priors.items()):
        lines.append(f"| {fam}:{side} | {w.get('kernel', '?')} | {w.get('gflops_median'):.1f} |")
    lines.append("")
    return "\n".join(lines) + "\n"


def _render_ladder(gate) -> str:
    lines = ["## 5. Candidate deck — gate verdicts", "",
             "CPU-gate legality only. Legal rows become candidates for the",
             "first TTY campaign; illegal rows are recorded so they can never",
             "sneak into a deck by accident.", ""]
    for fam, rows in gate.items():
        lines.append(f"### {fam}")
        lines.append("")
        lines.append("| tile | verdict | reason |")
        lines.append("|---|---|---|")
        for r in rows:
            tile = r["tile"]
            du = tile.get("DepthU", "-")
            tile_s = (f"{tile.get('MacroTile')}/{tile.get('ThreadTile')}"
                      f" VW{tile.get('VectorWidth')} DU{du}")
            why = (r["why"] or "ok").replace("\n", " ")[:80]
            verdict = "legal" if r["legal"] else "illegal"
            lines.append(f"| {tile_s} | {verdict} | {why} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def _render_open(p) -> str:
    lines = ["## 6. Still needs the TTY", "",
             "Nothing in this document is a measurement. Every claim below is a",
             "prior; closing any of them requires one isolated TTY run per cell.",
             "",
             "- [ ] the native arm at every cell — `oto tune` in the TTY",
             "- [ ] the floor/steal decision — only after the first native run",
             "- [ ] CC:256/512 AF4/4 adoption question — needs silicon, TTY only",
             "- [ ] clock-speed normalisation — `oto tune` handles it; do not quote",
             "      absolute GFLOP/s without it", ""]
    return "\n".join(lines) + "\n"


def consult(profile, base_dir=None, starter_text: str = "",
            out: Path | None = None, force: bool = False) -> dict[str, Any]:
    """Draft potential_configs markdown for ``profile``. CPU-only."""
    base = Path(base_dir) if base_dir else Path.cwd()
    profile = _loader.resolve_profile(profile)
    if out is None:
        out = Path(base / f"{profile.codename}_potential_configs.md")
    else:
        out = Path(out)
    if out.exists() and not force:
        return {"status": "refused", "out": str(out),
                "reason": "exists; pass force=True to overwrite"}
    priors = _corpus_priors(base)
    gate = _gate_ladder(base, profile)
    md = "".join([_render_device(profile, base), _render_ceilings(profile, priors),
                  _render_taxa(profile), _render_priors(priors),
                  _render_ladder(gate), _render_open(profile)])
    out.write_text(md)
    return {"status": "success", "out": str(out),
            "priors": len(priors),
            "legal_rows": sum(1 for rows in gate.values() for r in rows if r["legal"]),
            "illegal_rows": sum(1 for rows in gate.values() for r in rows if not r["legal"])}


if __name__ == "__main__":
    import sys

    prof = _loader.current_profile()
    print(json.dumps(consult(prof), indent=2))
    sys.exit(0)
