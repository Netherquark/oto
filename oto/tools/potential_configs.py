"""Automated potential_configs.md generator from run outputs.

Owns: synthesising a potential_configs.md from kernel_db + acceptance report +
profile + the measured corpus. Does NOT own the workflow or the agents.

Public API: generate(profile, base_dir) -> str.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from oto.device.profile import DeviceProfile
from oto.runners.paths import results_dir as _results_dir


def _load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text())
    except (json.JSONDecodeError, OSError):
        return None


def generate(profile: DeviceProfile, base_dir: Path) -> str:
    """Generate potential_configs.md for the tuning corpus. ``profile`` is the device to tune."""
    base_dir = Path(base_dir)
    out: list[str] = [
        f"# potential_configs.md — {profile.codename}",
        "",
        "Auto-generated by oto.tools.potential_configs. Every number below",
        "is read from the run's own artifacts; nothing is hand-transcribed.",
        "",
        "## Profile",
        f"- codename: {profile.codename}",
        f"- num_cus: {profile.num_cus}",
        f"- max_clock_mhz: {profile.max_clock_mhz}",
        f"- families: {', '.join(sorted(profile.family_shapes))}",
        f"- spoof_reference: {profile.spoof_reference or '(none — native only)'}",
        "",
    ]
    out.extend(_corpus_section(profile, base_dir))
    out.extend(_acceptance_section(profile, base_dir))
    out.extend(_citations())
    return "\n".join(out) + "\n"


def _floor_prefix(profile: DeviceProfile) -> str:
    """Generate potential_configs.md for the tuning corpus. ``profile`` is the device to tune."""
    ref = profile.spoof_reference or ""
    return f"{ref}_ref" if ref else "_ref_"


def _corpus_section(profile: DeviceProfile, base_dir: Path) -> list[str]:
    """The `## Corpus` + per-run stats block.

    ``profile`` -- the device profile to tune.
    """
    kb = _results_dir(base_dir, profile.codename) / "analysis" / "kernel_db.json"
    db = _load_json(kb)
    if not isinstance(db, dict):
        return ["## Corpus: (no kernel_db.json found)", ""]
    prefix = _floor_prefix(profile=profile,)
    total_rows = sum(len(v) for v in db.values())
    floor_rows = sum(len(v) for k, v in db.items() if k.startswith(prefix))
    lines = ["## Corpus",
             f"- runs: {len(db)}",
             f"- kernel-shape rows: {total_rows}",
             f"- native rows: {total_rows - floor_rows}",
             f"- floor rows: {floor_rows}",
             "",
             "## Per-run row counts"]
    lines.extend(f"- {run_id}: {len(db[run_id])} rows" for run_id in sorted(db))
    lines.append("")
    return lines


def _acceptance_section(profile: DeviceProfile, base_dir: Path) -> list[str]:
    """The like-for-like acceptance + verdict anatomy + ranked attack plan.

    ``profile`` -- the device profile to tune.
    """
    ar = _load_json(_results_dir(base_dir, profile.codename) / "acceptance_report.json")
    if not isinstance(ar, dict):
        return []
    verdicts = ar.get("per_cell_verdicts", [],)
    tally = {"WIN": 0, "TIE": 0, "LOSS": 0}
    for v in verdicts:
        tally[v.get("verdict", "",)] = tally.get(v.get("verdict", "",), 0,) + 1
    overall = ar.get("overall_pass",)
    lines = ["## Acceptance (like-for-like)",
             f"- cells: {len(verdicts)}  (WIN {tally['WIN']} / TIE {tally['TIE']} / LOSS {tally['LOSS']})",
             f"- overall_pass: {overall}",
             f"- reference run: {ar.get('reference_run_id', '?',)}",
             "- admission rule: protocol='family' like-for-like (see docs/comparability.md)",
             "",
             "## Verdict anatomy"]
    lines.extend(_anatomy_lines(verdicts))
    lines.extend(_attack_plan(verdicts))
    orange = ar.get("orange_list",) or []
    if orange:
        lines.append("## Orange list (attention, not failures)")
        for item in orange:
            if isinstance(item, dict):
                lines.append(
                    "- {fam} {shape}: {g} GFlops ({pct}% of ceiling)".format(
                        fam=item.get("family", "?",),
                        shape=item.get("shape", "?",),
                        g=item.get("median_gflops", "?",),
                        pct=item.get("pct_of_ceiling", "?",)))
            else:
                lines.append(f"- {item}")
        lines.append("")
    lines.append("## Realistic ceilings (client-reported units)")
    lines.extend(f"- {fam}: {profile.realistic_ceilings[fam]}"
                 for fam in sorted(profile.realistic_ceilings))
    lines.append("")
    return lines


def _anatomy_lines(verdicts: list[dict[str, Any]]) -> list[str]:
    """One line per cell: family shape native/floor medians and delta."""
    lines = ["| family | shape | native median | floor median | delta_pct | verdict |",
             "|---|---|---|---|---|---|"]
    for v in sorted(verdicts, key=lambda v: (v.get("family", ""), str(v.get("shape", "")))):
        nm, sm = v.get("native_median"), v.get("spoof_median")
        d = v.get("delta_pct")
        lines.append(
            "| {fam} | {shape} | {nm} | {sm} | {d} | {verdict} |".format(
                fam=v.get("family", "?"),
                shape=v.get("shape", "?"),
                nm=f"{nm:.3f}" if isinstance(nm, (int, float)) else "?",
                sm=f"{sm:.3f}" if isinstance(sm, (int, float)) else "?",
                d=f"{d:+.2f}%" if isinstance(d, (int, float)) else "?",
                verdict=v.get("verdict", "?"),
            ))
    lines.append("")
    return lines


def _attack_plan(verdicts: list[dict[str, Any]]) -> list[str]:
    """The ranked work order: LOSSes by size, then TIEs closest to flipping."""
    def gap(v: dict[str, Any]) -> float:
        d = v.get("delta_pct")
        return d if isinstance(d, (int, float)) else 0.0

    losses = [v for v in verdicts if v.get("verdict") == "LOSS"]
    ties = [v for v in verdicts if v.get("verdict") == "TIE"]
    losses.sort(key=gap)
    ties.sort(key=gap)
    lines = ["## Ranked attack plan"]
    if not losses and not ties:
        lines.append("- nothing outstanding over the floor (every cell WIN)")
    else:
        for i, v in enumerate(losses, 1):
            lines.append(f"{i}. LOSS {v.get('family')} {v.get('shape')} "
                         f"({gap(v):+.2f}%) — floor beats native; attack this cell first")
        offset = len(losses)
        for i, v in enumerate(ties, 1):
            lines.append(f"{offset + i}. TIE {v.get('family')} {v.get('shape')} "
                         f"({gap(v):+.2f}%) — margin too thin to call; widen the search here")
    lines.append("")
    return lines


def _citations() -> list[str]:
    return ["## Research citations",
            "- Verdicts and ceilings: this run's own kernel_db + acceptance report.",
            "- Like-for-like admission rule (protocol='family'): docs/comparability.md.",
            "- Occupancy / register-file model: oto/tensile/gates/vgpr_model.py.",
            "- Knob semantics and measured patterns: kernel_tuning_research.md,",
            "  knowledge_base.md (the §R register), potential_configs.md (the hand-tuned why).",
            ""]
